export const COMPETENCY_INTRO = `Clinical psychologists use their knowledge of psychology and mental health for the assessment, diagnosis, formulation, treatment, and prevention of psychological problems and mental illness across the lifespan. They research psychological problems and use their psychological knowledge to develop scientifically based approaches to improve mental health and wellbeing.

Consumers of the services of clinical psychologists are individuals, groups and organisations, including members of the public, families and carers, community groups, medical and health practitioners and specialists, health departments, hospitals and community practices, national, state or local government or non-government organisations, welfare agencies, educational institutions, defence, justice and community services, and tribunals, courts and medico-legal officers and bodies.

Specific services of clinical psychologists include the assessment and treatment of a range of mental health problems, such as anxiety, depression, substance dependence, pain and somatic symptoms, schizophrenia, bipolar disorder, bulimia, anorexia, binge eating, conduct disorder, separation anxiety, attention deficit and hyperactivity disorder, autism spectrum disorders, and borderline, antisocial and other personality disorders. Clinical psychologists also consult more broadly with the community on mental health programs, policies, and practices related to children, adolescents, adults and older adults.

To assure consumers that a clinical psychologist is capable of providing the services required, all endorsed clinical psychologists must be competent in the eight core competence areas of clinical psychology. Additionally, all clinical psychologists must be cognisant of the APS Code of Ethics, General Principle 'B.1. Competence' when considering whether they are able to provide a psychological service.`;

